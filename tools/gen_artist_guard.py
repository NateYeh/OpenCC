#!/usr/bin/env python3
"""產生藝名保護條目（繁簡雙 key）。

用法：python3 tools/gen_artist_guard.py > data/overlay/s2twp-overlay-phrases.txt

背景
----
OpenCC 的 chain1（STPhrases / STCharacters）跑在**簡體輸入**上，key 是簡體。
但要保護的藝名常已是**繁體**（「范曉萱」「張震嶽」），此時輸入不會被
chain1 認出，只能靠 mpdp 分割詞表把整詞保住，再由 overlay 自我映射擋掉
「范→範」等過度轉換。

因此每個名字需要兩個條目：
  1. 簡體 key → 繁體 value   （擋掉「簡體輸入被轉錯」）
  2. 繁體 key → 繁體 value   （擋掉「繁體輸入被轉壞」）

mpdp 詞表由 build_mpdp_dict.py 依「規則 4」自動補 t2s 簡體形，
故兩個 key 都會進入分割詞表。
"""

from __future__ import annotations

# (繁體正名, 簡體形)
# 「簡體形」用於產生簡體 key；留空則由 t2s 自動推導。
ARTISTS: list[tuple[str, str]] = [
    # ── 姓「于」：單字 于→於，藝名保留「于」──
    # ⚠️ 只收 3 字以上的名字。2 字名（于震、于海、于正…）在 mpdp 分割下
    #    會與「过于震驚」等極常見詞組競爭，把「于」誤判成藝名：
    #    實測「過于震驚」→「過于震驚」❌（15 個 2 字條目共造成 315 個副作用）。
    #    upstream 的人名條目（岳不群、游坦之）同樣皆為 3 字以上。
    ('于文文', '于文文'),
    ('于果', '于果'),
    ('于朦朧', '于朦胧'),
    ('于恆', '于恒'),
    ('于謙', '于谦'),
    # ── 姓「范」：單字 范→範，藝名保留「范」──
    ('范曉萱', '范晓萱'),
    ('范瑋琪', '范玮琪'),
    ('范丞丞', '范丞丞'),
    ('范世錡', '范世锜'),
    ('范少勳', '范少勋'),
    ('范鴻軒', '范鸿轩'),
    ('范志博', '范志博'),
    ('范薇', '范薇'),
    ('范滄東', '范沧东'),
    ('范逸臣', '范逸臣'),
    # ── 姓「游」：單字 游→遊，藝名保留「游」──
    ('游鴻明', '游鸿明'),
    ('游安迪', '游安迪'),
    ('游智淵', '游智渊'),
    ('游乃翔', '游乃翔'),
    ('游昌鎮', '游昌镇'),
    ('游耀忠', '游耀忠'),
    # ── 姓「朴」：韓國藝人用「朴」──
    ('朴鯊', '朴鲨'),
    ('朴有天', '朴有天'),
    ('朴信惠', '朴信惠'),
    ('朴寶英', '朴宝英'),
    ('朴政珉', '朴政珉'),
    ('朴有鎮', '朴有镇'),
    ('朴俊亨', '朴俊亨'),
    ('朴海養', '朴海养'),
    ('朴寶劍', '朴宝剑'),
    ('朴燦星', '朴灿星'),
    ('朴沙星', '朴沙星'),
    ('朴樹', '朴树'),
    # ── 姓「岳」：單字 岳→嶽，藝名保留「岳」──
    ('岳雲鵬', '岳云鹏'),
    ('岳飛', '岳飞'),
    ('岳麗娜', '岳丽娜'),
    # ── 其他──
    ('回音哥', '回音哥'),
    ('干露', '干露'),
    ('鍾欣潼', '钟欣潼'),
    ('钟不悔', '钟不悔'),
    ('汪蘇瀧', '汪苏泷'),
    ('馬郁', '马郁'),
    ('張震嶽', '张震岳'),
]


def main() -> None:
    """輸出 overlay 條目到 stdout。"""
    lines: list[str] = []
    seen: set[tuple[str, str]] = set()
    for trad, simp in ARTISTS:
        for key in {simp, trad}:
            if (key, trad) in seen:
                continue
            seen.add((key, trad))
            lines.append(f'{key}\t{trad}')
    print('\n'.join(lines))


if __name__ == '__main__':
    main()
